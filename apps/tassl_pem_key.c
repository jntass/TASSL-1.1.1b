#include <ctype.h>
#include <string.h>
#include "openssl/bn.h"
#include "openssl/ec.h"
#include "openssl/evp.h"
#include "openssl/pem.h"
#include "apps.h"

#define INPUT_BUF_LEN 1024
#define PRIVATE_KEY_LEN 40
#define PUBLIC_KEY_LEN 91

const OPTIONS tassl_pem_key_options[] = {
    {NULL},
};

static int tassl_hsm_sm2_pem_key_main( const char *lmk_pri, const char *der_pub, const char *out )
{
    BIO *mem_b = NULL;
    EC_KEY *eckey = NULL;
    BIGNUM *pri_key = NULL;
    const uint8_t *p = NULL;
    char input_buf[INPUT_BUF_LEN];
    uint8_t *pri_key_buf = NULL;
    long pri_key_len;
    uint8_t *pub_key_buf = NULL;
    long pub_key_len;
    int ret, rv = 0;

    //First. get private key encrypted by LMK
    memset(input_buf, 0, INPUT_BUF_LEN);
    if( NULL == lmk_pri )
    {
        BIO_printf(bio_out, "input private key encrypted by LMK:");
        if( 0 >= BIO_gets(bio_in, input_buf, INPUT_BUF_LEN) )
        {
            BIO_printf(bio_err, "input error\n");
            goto err;
        }
        if( !isxdigit(input_buf[strlen(input_buf)-1]) ) //delete '\n'
        {
            input_buf[strlen(input_buf)-1] = '\0';
        }
    }
    else
    {
        memcpy(input_buf, lmk_pri, strlen(lmk_pri));
    }

    //HEX to BIN
    if( NULL != pri_key_buf )
    {
        OPENSSL_free(pri_key_buf);
        pri_key_buf = NULL;
    }
    pri_key_buf = OPENSSL_hexstr2buf(input_buf, &pri_key_len);
    if( (pri_key_buf == NULL) || (PRIVATE_KEY_LEN != pri_key_len) )
    {
        BIO_printf(bio_err, "private key error\n");
        goto err;
    }

    //BIN to BN
    pri_key = BN_bin2bn(pri_key_buf, pri_key_len, NULL);
    if(NULL == pri_key)
    {
        BIO_printf(bio_err, "BN_bin2bn fail!\n");
        goto err;
    }

    //Second. get public key encoded to DER
    memset(input_buf, 0, INPUT_BUF_LEN);
    if( NULL == der_pub )
    {
        BIO_printf(bio_out, "input public key(DER):");
        if( 0 >= BIO_gets(bio_in, input_buf, INPUT_BUF_LEN) )
        {
            BIO_printf(bio_err, "input error\n");
            goto err;
        }
        if( !isxdigit(input_buf[strlen(input_buf)-1]) ) //delete '\n'
        {
            input_buf[strlen(input_buf)-1] = '\0';
        }
    }
    else
    {
        memcpy(input_buf, der_pub, strlen(der_pub));
    }

    //HEX to BIN
    if( NULL != pub_key_buf )
    {
        OPENSSL_free(pub_key_buf);
        pub_key_buf = NULL;
    }
    pub_key_buf = OPENSSL_hexstr2buf(input_buf, &pub_key_len);
    if( (pub_key_buf == NULL) || (pub_key_len <= 0) )
    {
        BIO_printf(bio_err, "public key error\n");
        goto err;
    }
   
    //BIN DER public key to internal EC KEY
    p = pub_key_buf;
    eckey = d2i_EC_PUBKEY(NULL, &p, pub_key_len);
    if(NULL == eckey)
    {
        BIO_printf(bio_err, "EC_KEY_new fail!\n");
        goto err;
    }
    
    //set private key to EC KEY
    ret = EC_KEY_set_private_key(eckey, pri_key);
    if(1 != ret)
    {
        BIO_printf(bio_err, "EC_KEY_set_private_key fail!\n");
        goto err;
    }
    EC_KEY_set_flags(eckey, EC_FLAG_TASSHSM_ENGINE); //note: before write key that generated by tasshsm engine to PEM, must set this flag

    //Third. write PEM
    memset(input_buf, 0, INPUT_BUF_LEN);
    if( NULL == out )
    {
        BIO_printf(bio_out, "input key filename:");
        if( 0 >= BIO_gets(bio_in, input_buf, INPUT_BUF_LEN) )
        {
            BIO_printf(bio_err, "input error\n");
            goto err;
        }
        if( !isxdigit(input_buf[strlen(input_buf)-1]) ) //delete '\n'
        {
            input_buf[strlen(input_buf)-1] = '\0';
        }
    }
    else
    {
        memcpy(input_buf, out, strlen(out));
    }

    mem_b=BIO_new_file(input_buf,"w");
    if(mem_b == NULL)
    {
        BIO_printf(bio_err, "open key_outfile %s fail!\n", input_buf);
        goto err;
    }

    ret= PEM_write_bio_ECPrivateKey(mem_b, eckey, NULL, NULL, 0, NULL, NULL);
    if(ret!=1)
    {
        goto err;
    }
    BIO_free(mem_b);
    BIO_printf(bio_out, "PEM key write success\n");
    rv = 1;
err:
    if(eckey) EC_KEY_free(eckey);
    if(pri_key) BN_free(pri_key);
    if(pri_key_buf) OPENSSL_free(pri_key_buf);
    if(pub_key_buf) OPENSSL_free(pub_key_buf);
    return rv;
}

typedef enum
{
    DEV_TYPE_NONE = 0,
    DEV_TYPE_HSM  = 1,
    DEV_TYPE_CARD = 2,
}DEV_TYPE_E;

typedef enum
{
    KEY_TYPE_NONE = 0,
    KEY_TYPE_SM2  = 1,
    KEY_TYPE_RSA  = 2,
}KEY_TYPE_E;

#define DEV_TYPE_HSM_OPTION  "-hsm"
#define DEV_TYPE_CARD_OPTION "-card"
#define KEY_TYPE_SM2_OPTION  "-sm2"
#define KEY_TYPE_RSA_OPTION  "-rsa"
#define LMK_PRI_KEY_OPTION   "-lmk_pri"
#define DER_PUB_KEY_OPTION   "-der_pub"
#define OUTKEY_FILE_OPTION   "-out"

#define USAGE    "tassl_pem_key\n\t-dev_type\n\t-key_type\n\t-lmk_pri key\n\t-der_pub key\n\t-out file"

int tassl_pem_key_main( int argc, char *argv[] )
{
    int rv = 0;
    DEV_TYPE_E dev_type = DEV_TYPE_NONE;
    KEY_TYPE_E key_type = KEY_TYPE_NONE;
    const char *lmk_pri = NULL;
    const char *der_pub = NULL;
    const char *out = NULL;

    for( ; argc > 0; argc--, argv++ )
    {
        if( 0 == strncasecmp(*argv, DEV_TYPE_HSM_OPTION, strlen(DEV_TYPE_HSM_OPTION)) )
        {
            dev_type = DEV_TYPE_HSM;
        }
        else if( 0 == strncasecmp(*argv, DEV_TYPE_CARD_OPTION, strlen(DEV_TYPE_CARD_OPTION)) )
        {
            dev_type = DEV_TYPE_CARD;
        }
        else if( 0 == strncasecmp(*argv, KEY_TYPE_SM2_OPTION, strlen(KEY_TYPE_SM2_OPTION)) )
        {
            key_type = KEY_TYPE_SM2;
        }
        else if( 0 == strncasecmp(*argv, KEY_TYPE_RSA_OPTION, strlen(KEY_TYPE_RSA_OPTION)) )
        {
            key_type = KEY_TYPE_RSA;
        }
        else if( 0 == strncasecmp(*argv, LMK_PRI_KEY_OPTION, strlen(LMK_PRI_KEY_OPTION)) )
        {
            lmk_pri = *(argv+1);
        }
        else if( 0 == strncasecmp(*argv, DER_PUB_KEY_OPTION, strlen(DER_PUB_KEY_OPTION)) )
        {
            der_pub = *(argv+1);
        }
        else if( 0 == strncasecmp(*argv, OUTKEY_FILE_OPTION, strlen(OUTKEY_FILE_OPTION)) )
        {
            out = *(argv+1);
        }
    }

    if( (DEV_TYPE_HSM == dev_type) && (KEY_TYPE_SM2 == key_type) )
    {
        rv = tassl_hsm_sm2_pem_key_main(lmk_pri, der_pub, out);
    }

    if(!rv)
        BIO_printf(bio_err, "Usage: openssl %s\n", USAGE);
    return rv;
}
